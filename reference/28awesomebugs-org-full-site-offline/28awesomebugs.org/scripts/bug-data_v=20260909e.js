function generateRandomBirthday() {
    const start = new Date(2000, 0, 1);
    const end = new Date(2020, 11, 31);
    const birthday = new Date(start.getTime() + Math.random() * (end.getTime() - start.getTime()));
    const options = { year: 'numeric', month: 'long', day: 'numeric' };
    return birthday.toLocaleDateString(undefined, options);
}

function generateDeathDate() {
    const now = new Date();
    const options = { year: 'numeric', month: 'long', day: 'numeric' };
    return now.toLocaleDateString(undefined, options);
}

function getFullBugImagePool() {
    var pool = bugImages.slice();
    var purchaseKey = '28bugs_bugPurchases';
    var p = null;
    try { p = JSON.parse(localStorage.getItem(purchaseKey)); } catch (_) { p = null; }
    if (p && typeof p === 'object') {
        for (var key in p) {
            if (p[key] && key.match(/^breadlight\d+$/)) {
                var match = key.match(/\d+/);
                if (match) {
                    var num = match[0];
                    var imgPath = 'src/elliebugs/elliebug' + num + '.png';
                    pool.push(imgPath);
                }
            }
        }
    }
    return pool;
}

function getRandomBugImage() {
    var pool = getFullBugImagePool();
    return pool[Math.floor(Math.random() * pool.length)];
}

function getRandomBugName() {
    return bugNames[Math.floor(Math.random() * bugNames.length)];
}

function getRandomBugBackstory() {
    return bugBackstories[Math.floor(Math.random() * bugBackstories.length)] || defaultBackstory;
}

function getBugDataForImage(src) {
    if (!window.BugRoster) return null;
    
    var relative = src;
    try { relative = new URL(src).pathname.replace(/^\//, ''); } catch (_) {}
    return window.BugRoster.find(function(b) { return b.image === relative; }) || null;
}

function getRandomDeathMessage() {
    if (!deathMessages.length) return 'Natural causes';
    return deathMessages[Math.floor(Math.random() * deathMessages.length)];
}

