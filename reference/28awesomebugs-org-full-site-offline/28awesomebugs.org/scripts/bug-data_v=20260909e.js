(function attachBugDataSync() {
    function uniqueNames(arr) {
        return Array.from(new Set((arr || []).map(n => String(n).trim()).filter(Boolean)));
    }
    function readNamesFromLS(objectsKey, namesKey) {
        let names = [];
        let objs = [];
        try { objs = JSON.parse(localStorage.getItem(objectsKey) || '[]'); } catch {}
        if (Array.isArray(objs) && objs.length) {
            names = names.concat(objs.map(o => o && o.name).filter(Boolean));
        }

        let plain = [];
        try { plain = JSON.parse(localStorage.getItem(namesKey) || '[]'); } catch {}
        if (Array.isArray(plain) && plain.length) {
            names = names.concat(plain);
        }
        return uniqueNames(names);
    }

    function syncFromLocalStorage() {
        if (!window.BugData) return;
        const fans = readNamesFromLS('28bugs_supporters', '28bugs_supporters_names');
        const fiends = readNamesFromLS('28bugs_haters', '28bugs_haters_names');

        if (fans.length) window.BugData.fansList = fans;
        if (fiends.length) window.BugData.fiendsList = fiends;
    }

    
    window.BugData.syncFromLocalStorage = syncFromLocalStorage;
    syncFromLocalStorage();

    
    window.addEventListener('storage', (e) => {
        if (!e.key || !('28bugs_supporters' === e.key || '28bugs_haters' === e.key || '28bugs_supporters_names' === e.key || '28bugs_haters_names' === e.key)) return;
        syncFromLocalStorage();
        try { document.dispatchEvent(new Event('fansFiendsUpdated')); } catch {}
    });
})();
